export function translate(key: string, language: SupportedLanguage = 'English', replacements?: Record<string, string>): string {
  const langTranslations = TRANSLATIONS[language];
  if (!langTranslations) return TRANSLATIONS['English'][key] || key;
  let text = langTranslations[key] || TRANSLATIONS['English'][key] || key;
  if (replacements) {
    Object.entries(replacements).forEach(([k, v]) => {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    });
  }
  return text;
}
